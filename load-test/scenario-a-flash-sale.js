// 情境 A「開賣瞬間」(設計文件第 13 節 / docs/handover-M7-loadtest.md)。
// 30 秒 ramp 至 2000 VU,全部打同一票種(預設庫存 1000),ramp 完成後再持續 2 分鐘。
//
// 前置:
//   1. 已執行過 load-test/setup-users.js(至少註冊 SCENARIO_A_VUS 個帳號)。
//   2. 後端啟動前已調高限流閾值(SECKILL_RL_IP / SECKILL_RL_GLOBAL 等 env),否則單 IP
//      10/s 會把整場壓測卡在 10 QPS。見 load-test/README.md。
//   3. 本腳本的 setup() 會自動建立、發布並 warmup 一個專用活動與票種,不需手動準備。
//
// 執行:
//   k6 run load-test/scenario-a-flash-sale.js
//   即時面板:K6_WEB_DASHBOARD=true k6 run load-test/scenario-a-flash-sale.js
//
// 設計取捨(自主決策,結尾報告會重述):每個 VU 對應一位壓測使用者,僅在自己的搶購結果
// 定局(SUCCESS/FAIL,或逾時仍未定局)之後才停止對該票種送出請求,改為原地 sleep 撐滿測試
// 時長,不會無限重試造成大量「重複購買」雜訊——這樣「30 秒 ramp + 持續 2 分鐘」量到的才是
// 開賣瞬間的真實併發競爭,而非同一使用者對自己的重複攻擊。

import http from 'k6/http';
import { check, sleep } from 'k6';
import { Counter, Trend } from 'k6/metrics';
import { BASE_URL, ADMIN_USERNAME, ADMIN_PASSWORD, USER_PASSWORD, usernameFor, jsonHeaders } from './lib/config.js';

const TARGET_VUS = Number(__ENV.SCENARIO_A_VUS || 2000);
const RAMP_SECONDS = Number(__ENV.SCENARIO_A_RAMP_SECONDS || 30);
const HOLD_SECONDS = Number(__ENV.SCENARIO_A_HOLD_SECONDS || 120);
const STOCK = Number(__ENV.SCENARIO_A_STOCK || 1000);
const USER_OFFSET = Number(__ENV.SCENARIO_A_USER_OFFSET || 0);
const RESULT_POLL_ATTEMPTS = Number(__ENV.RESULT_POLL_ATTEMPTS || 10);

const successCount = new Counter('seckill_success');
const soldOutCount = new Counter('seckill_soldout');
const duplicateCount = new Counter('seckill_duplicate');
const rateLimitedCount = new Counter('seckill_ratelimited');
const otherFailCount = new Counter('seckill_other_fail');
const queuingUnresolvedCount = new Counter('seckill_queuing_unresolved');
const settleLatency = new Trend('seckill_settle_latency_ms', true);

export const options = {
  scenarios: {
    flashSale: {
      executor: 'ramping-vus',
      startVUs: 0,
      stages: [
        { duration: `${RAMP_SECONDS}s`, target: TARGET_VUS },
        { duration: `${HOLD_SECONDS}s`, target: TARGET_VUS },
      ],
      gracefulRampDown: '30s',
    },
  },
  thresholds: {
    // 對齊設計文件第 13 節驗收:搶購接口 p99 < 300ms(Redis 路徑)。本機單機壓 2000 VU
    // 屬資訊性觀察(受本機硬體與 loopback 影響),未達標不代表腳本錯誤,結果如實寫進報告。
    'http_req_duration{name:purchase}': ['p(99)<300'],
  },
};

export function setup() {
  const loginRes = http.post(
    `${BASE_URL}/api/v1/auth/login`,
    JSON.stringify({ username: ADMIN_USERNAME, password: ADMIN_PASSWORD }),
    jsonHeaders(null, 'setup'),
  );
  const adminToken = loginRes.json('data.accessToken');
  if (!adminToken) throw new Error(`[setup] admin login failed: ${loginRes.status} ${loginRes.body}`);

  const auth = jsonHeaders(adminToken, 'setup');
  const now = Date.now();
  const eventTitle = `LoadTest Scenario A ${now}`;

  const eventRes = http.post(
    `${BASE_URL}/api/v1/admin/events`,
    JSON.stringify({
      title: eventTitle,
      description: 'k6 load test event (auto-generated by scenario-a-flash-sale.js, safe to delete)',
      venue: 'Load Test Venue',
      eventTime: new Date(now + 24 * 3600 * 1000).toISOString(),
    }),
    auth,
  );
  const eventId = eventRes.json('data.id');
  if (!eventId) throw new Error(`[setup] create event failed: ${eventRes.status} ${eventRes.body}`);

  // 票種開賣時窗要蓋住 ramp + hold + 結果輪詢緩衝,避免測到一半票種先行「已結束」。
  const windowMs = (RAMP_SECONDS + HOLD_SECONDS) * 1000 + 5 * 60 * 1000;
  const ttRes = http.post(
    `${BASE_URL}/api/v1/admin/ticket-types`,
    JSON.stringify({
      eventId,
      name: 'Scenario A Ticket',
      price: 100,
      totalStock: STOCK,
      seckillStart: new Date(now - 60 * 1000).toISOString(),
      seckillEnd: new Date(now + windowMs).toISOString(),
    }),
    auth,
  );
  const ticketTypeId = ttRes.json('data.id');
  if (!ticketTypeId) throw new Error(`[setup] create ticket type failed: ${ttRes.status} ${ttRes.body}`);

  const publishRes = http.put(
    `${BASE_URL}/api/v1/admin/events/${eventId}`,
    JSON.stringify({
      title: eventTitle,
      description: 'k6 load test event (auto-generated by scenario-a-flash-sale.js, safe to delete)',
      venue: 'Load Test Venue',
      coverImageUrl: null,
      featured: false,
      featuredOrder: null,
      eventTime: new Date(now + 24 * 3600 * 1000).toISOString(),
      status: 'PUBLISHED',
    }),
    auth,
  );
  if (publishRes.json('code') !== 0) {
    throw new Error(`[setup] publish event failed: ${publishRes.status} ${publishRes.body}`);
  }

  const warmupRes = http.post(`${BASE_URL}/api/v1/admin/ticket-types/${ticketTypeId}/warmup`, null, auth);
  if (warmupRes.json('code') !== 0) {
    throw new Error(`[setup] warmup failed: ${warmupRes.status} ${warmupRes.body}`);
  }

  console.log(`[setup] eventId=${eventId} ticketTypeId=${ticketTypeId} stock=${STOCK} title=${eventTitle}`);
  return { ticketTypeId, eventId };
}

let settled = false; // 本 VU 是否已有定局結果,避免對同一票種重複搶購

export default function (data) {
  if (settled) {
    sleep(1);
    return;
  }

  const username = usernameFor(USER_OFFSET + __VU - 1);

  const loginRes = http.post(
    `${BASE_URL}/api/v1/auth/login`,
    JSON.stringify({ username, password: USER_PASSWORD }),
    jsonHeaders(null, 'login'),
  );
  const token = loginRes.json('data.accessToken');
  if (!token) {
    console.error(`[vu ${__VU}] login failed username=${username} status=${loginRes.status} body=${loginRes.body}`);
    otherFailCount.add(1);
    settled = true;
    return;
  }

  const tokenRes = http.post(
    `${BASE_URL}/api/v1/seckill/token`,
    JSON.stringify({ ticketTypeId: data.ticketTypeId }),
    jsonHeaders(token, 'seckillToken'),
  );
  const seckillToken = tokenRes.json('data.token');
  if (!seckillToken) {
    otherFailCount.add(1);
    settled = true;
    return;
  }

  const startedAt = Date.now();
  const purchaseRes = http.post(
    `${BASE_URL}/api/v1/seckill/purchase`,
    JSON.stringify({ ticketTypeId: data.ticketTypeId, token: seckillToken }),
    jsonHeaders(token, 'purchase'),
  );
  const purchaseBody = purchaseRes.json();
  check(purchaseRes, {
    'purchase responded with envelope': () => purchaseBody && typeof purchaseBody.code === 'number',
  });

  switch (purchaseBody && purchaseBody.code) {
    case 0: {
      const requestId = purchaseBody.data.requestId;
      let resolved = false;
      for (let i = 0; i < RESULT_POLL_ATTEMPTS && !resolved; i++) {
        sleep(1);
        const resultRes = http.get(`${BASE_URL}/api/v1/seckill/result/${requestId}`, jsonHeaders(token, 'result'));
        const resultBody = resultRes.json();
        const status = resultBody && resultBody.data && resultBody.data.status;
        if (status === 'SUCCESS') {
          successCount.add(1);
          settleLatency.add(Date.now() - startedAt);
          resolved = true;
        } else if (status === 'FAIL') {
          otherFailCount.add(1);
          settleLatency.add(Date.now() - startedAt);
          resolved = true;
        }
      }
      // 逾時仍 QUEUING:代表壓測期間佇列尚未消化完畢,計入專屬計數器(對應設計文件驗收
      // 「流量結束後 2 分鐘內佇列積壓消化完畢」),不算作錯誤。
      if (!resolved) queuingUnresolvedCount.add(1);
      break;
    }
    case 3005:
      soldOutCount.add(1);
      break;
    case 3006:
      duplicateCount.add(1);
      break;
    case 3004:
      rateLimitedCount.add(1);
      break;
    default:
      otherFailCount.add(1);
      console.warn(
        `[vu ${__VU}] unexpected purchase response code=${purchaseBody && purchaseBody.code} msg=${purchaseBody && purchaseBody.message}`,
      );
  }

  settled = true;
}
