// 情境 B「持續高壓」(設計文件第 13 節 / docs/handover-M7-loadtest.md)。
// 1000 VU 恆定 10 分鐘,混合流量:70% 搶購、20% 查活動詳情、10% 輪詢結果。
//
// 前置:同 scenario-a-flash-sale.js(已跑過 setup-users.js;後端已調高限流閾值)。
//
// 執行:
//   k6 run load-test/scenario-b-sustained.js
//   即時面板:K6_WEB_DASHBOARD=true k6 run load-test/scenario-b-sustained.js
//
// 設計取捨(自主決策,結尾報告會重述):
// - 帳號池位移(預設從第 2000 號帳號開始,SCENARIO_B_USER_OFFSET),與情境 A 預設用的
//   0–1999 區段分開,雖然兩情境各自建立獨立票種、理論上不會互相影響,但分開比較乾淨。
// - 每位使用者一輪合法只能搶購成功一次(業務規則:每人限購一張)。10 分鐘內同一使用者
//   之後的「搶購」動作大多會回 3006(重複購買),票種售完後則回 3005——這是預期行為,
//   反映真實流量中使用者持續重試/刷新的型態,不是腳本錯誤。
// - 「輪詢結果」動作若該 VU 尚無 requestId(還沒送出過搶購),退化為「查活動詳情」。
// - 每輪迭代加入隨機思考時間(預設 1–3 秒,可用 THINK_TIME_MIN_MS / THINK_TIME_MAX_MS
//   覆寫),避免 1000 VU 零間隔狂打出不具代表性的極端 RPS。
// - 本情境的「搶購成功」計的是 purchase 端點受理成功(code=0),不逐一輪詢到底 SUCCESS/FAIL
//   ——輪詢會拖慢單一 VU 的節奏、稀釋「持續高壓」的意義。零超賣/零重複以壓測後呼叫
//   reconcile API 驗證(見 README),不依賴本腳本的計數器。

import http from 'k6/http';
import { check, sleep } from 'k6';
import { Counter } from 'k6/metrics';
import { BASE_URL, ADMIN_USERNAME, ADMIN_PASSWORD, USER_PASSWORD, usernameFor, jsonHeaders } from './lib/config.js';

const TARGET_VUS = Number(__ENV.SCENARIO_B_VUS || 1000);
const DURATION_SECONDS = Number(__ENV.SCENARIO_B_DURATION_SECONDS || 600);
const STOCK = Number(__ENV.SCENARIO_B_STOCK || 1500);
const USER_OFFSET = Number(__ENV.SCENARIO_B_USER_OFFSET || 2000);
const THINK_TIME_MIN_MS = Number(__ENV.THINK_TIME_MIN_MS || 1000);
const THINK_TIME_MAX_MS = Number(__ENV.THINK_TIME_MAX_MS || 3000);

const purchaseAttempt = new Counter('b_purchase_attempt');
const successCount = new Counter('b_seckill_accepted'); // 受理成功(code=0),非落庫結果
const soldOutCount = new Counter('b_seckill_soldout');
const duplicateCount = new Counter('b_seckill_duplicate');
const rateLimitedCount = new Counter('b_seckill_ratelimited');
const otherFailCount = new Counter('b_seckill_other_fail');
const queryCount = new Counter('b_query');
const pollCount = new Counter('b_poll');

export const options = {
  scenarios: {
    sustained: {
      executor: 'constant-vus',
      vus: TARGET_VUS,
      duration: `${DURATION_SECONDS}s`,
    },
  },
};

export function setup() {
  const loginRes = http.post(
    `${BASE_URL}/api/v1/auth/login`,
    JSON.stringify({ username: ADMIN_USERNAME, password: ADMIN_PASSWORD }),
    jsonHeaders(null, 'setup'),
  );
  const adminToken = loginRes.json('data.accessToken');
  if (!adminToken) throw new Error(`[setup] admin login failed: ${loginRes.status} ${loginRes.body}`);

  const auth = jsonHeaders(adminToken, 'setup');
  const now = Date.now();
  const eventTitle = `LoadTest Scenario B ${now}`;

  const eventRes = http.post(
    `${BASE_URL}/api/v1/admin/events`,
    JSON.stringify({
      title: eventTitle,
      description: 'k6 load test event (auto-generated by scenario-b-sustained.js, safe to delete)',
      venue: 'Load Test Venue',
      eventTime: new Date(now + 24 * 3600 * 1000).toISOString(),
    }),
    auth,
  );
  const eventId = eventRes.json('data.id');
  if (!eventId) throw new Error(`[setup] create event failed: ${eventRes.status} ${eventRes.body}`);

  const windowMs = DURATION_SECONDS * 1000 + 5 * 60 * 1000;
  const ttRes = http.post(
    `${BASE_URL}/api/v1/admin/ticket-types`,
    JSON.stringify({
      eventId,
      name: 'Scenario B Ticket',
      price: 100,
      totalStock: STOCK,
      seckillStart: new Date(now - 60 * 1000).toISOString(),
      seckillEnd: new Date(now + windowMs).toISOString(),
    }),
    auth,
  );
  const ticketTypeId = ttRes.json('data.id');
  if (!ticketTypeId) throw new Error(`[setup] create ticket type failed: ${ttRes.status} ${ttRes.body}`);

  const publishRes = http.put(
    `${BASE_URL}/api/v1/admin/events/${eventId}`,
    JSON.stringify({
      title: eventTitle,
      description: 'k6 load test event (auto-generated by scenario-b-sustained.js, safe to delete)',
      venue: 'Load Test Venue',
      coverImageUrl: null,
      featured: false,
      featuredOrder: null,
      eventTime: new Date(now + 24 * 3600 * 1000).toISOString(),
      status: 'PUBLISHED',
    }),
    auth,
  );
  if (publishRes.json('code') !== 0) {
    throw new Error(`[setup] publish event failed: ${publishRes.status} ${publishRes.body}`);
  }

  const warmupRes = http.post(`${BASE_URL}/api/v1/admin/ticket-types/${ticketTypeId}/warmup`, null, auth);
  if (warmupRes.json('code') !== 0) {
    throw new Error(`[setup] warmup failed: ${warmupRes.status} ${warmupRes.body}`);
  }

  console.log(`[setup] eventId=${eventId} ticketTypeId=${ticketTypeId} stock=${STOCK} title=${eventTitle}`);
  return { ticketTypeId, eventId };
}

let cachedToken = null;
let lastRequestId = null;

function ensureLogin(username) {
  if (cachedToken) return cachedToken;
  const loginRes = http.post(
    `${BASE_URL}/api/v1/auth/login`,
    JSON.stringify({ username, password: USER_PASSWORD }),
    jsonHeaders(null, 'login'),
  );
  cachedToken = loginRes.json('data.accessToken');
  if (!cachedToken) {
    console.error(`[vu ${__VU}] login failed username=${username} status=${loginRes.status} body=${loginRes.body}`);
  }
  return cachedToken;
}

function doPurchaseFlow(data, token) {
  purchaseAttempt.add(1);
  const tokenRes = http.post(
    `${BASE_URL}/api/v1/seckill/token`,
    JSON.stringify({ ticketTypeId: data.ticketTypeId }),
    jsonHeaders(token, 'seckillToken'),
  );
  const seckillToken = tokenRes.json('data.token');
  if (!seckillToken) {
    otherFailCount.add(1);
    return;
  }

  const purchaseRes = http.post(
    `${BASE_URL}/api/v1/seckill/purchase`,
    JSON.stringify({ ticketTypeId: data.ticketTypeId, token: seckillToken }),
    jsonHeaders(token, 'purchase'),
  );
  const body = purchaseRes.json();
  check(purchaseRes, { 'purchase responded with envelope': () => body && typeof body.code === 'number' });

  switch (body && body.code) {
    case 0:
      lastRequestId = body.data.requestId;
      successCount.add(1);
      break;
    case 3005:
      soldOutCount.add(1);
      break;
    case 3006:
      duplicateCount.add(1); // 預期:同一使用者第二次以後的搶購,見檔頭說明
      break;
    case 3004:
      rateLimitedCount.add(1);
      break;
    default:
      otherFailCount.add(1);
  }
}

function doQuery(data) {
  queryCount.add(1);
  http.get(`${BASE_URL}/api/v1/events/${data.eventId}`, { tags: { name: 'eventDetail' } });
}

// 回傳 true 代表本次真的送出了輪詢請求;false 代表尚無 requestId,呼叫端應退化為查詢。
function doPoll(token) {
  if (!lastRequestId) return false;
  pollCount.add(1);
  http.get(`${BASE_URL}/api/v1/seckill/result/${lastRequestId}`, jsonHeaders(token, 'result'));
  return true;
}

export default function (data) {
  const username = usernameFor(USER_OFFSET + __VU - 1);
  const token = ensureLogin(username);
  if (!token) {
    sleep(THINK_TIME_MAX_MS / 1000);
    return;
  }

  const roll = Math.random();
  if (roll < 0.7) {
    doPurchaseFlow(data, token);
  } else if (roll < 0.9) {
    doQuery(data);
  } else if (!doPoll(token)) {
    doQuery(data);
  }

  const thinkMs = THINK_TIME_MIN_MS + Math.random() * (THINK_TIME_MAX_MS - THINK_TIME_MIN_MS);
  sleep(thinkMs / 1000);
}
